        <p>This page explains cookies used by the eRequest Mo Portal, why they are used, and how you can manage them. We list cookies used by the application and identify third-party cookies whose details are controlled by their provider.</p>

        <h2>1. Cookies Used by the Portal</h2>
        <p>The portal uses these cookies for session security, remembering your cookie notice preference, and protecting sign-in and registration from automated abuse:</p>
        <ul>
            <li><strong>PHPSESSID (essential session cookie):</strong> A first-party cookie that connects your browser to server-side session state used for sign-in and security functions. It normally expires when you close your browser; the server may expire inactive sessions sooner.</li>
            <li><strong>ei_cookie_consent (preference cookie):</strong> A first-party cookie that remembers whether you accepted or declined the notice so it is not shown repeatedly. Declining only dismisses the notice; essential session and sign-in security cookies may still be used. It expires after one year.</li>
            <li><strong>Google reCAPTCHA cookies (third-party security):</strong> Google may set or read cookies when its reCAPTCHA widget loads on sign-in and registration pages. Cookie names and retention are controlled by Google. See <a href="https://policies.google.com/privacy" target="_blank" rel="noopener noreferrer">Google’s Privacy Policy</a> and <a href="https://policies.google.com/terms" target="_blank" rel="noopener noreferrer">Terms of Service</a>.</li>
        </ul>

        <h2>2. Browser Storage That Is Not a Cookie</h2>
        <p>Employee and administrator dashboards use browser local storage to remember the selected dashboard panel. This data stays in your browser and is separate from cookies. You can clear it through your browser settings.</p>

        <h2>3. Managing Cookies</h2>
        <p>You can block or delete cookies through your browser settings. Blocking the session cookie may prevent sign-in and other portal features from working. Choosing Decline dismisses the notice but does not disable the essential session cookie or Google reCAPTCHA used on sign-in and registration pages. Deleting <code>ei_cookie_consent</code> may cause the cookie notice to appear again. Google reCAPTCHA is provided by Google; its processing is subject to Google’s Privacy Policy and Terms of Service linked above.</p>

        <h2>4. More Information</h2>
