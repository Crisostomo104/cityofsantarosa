        <h2>Our Commitment to Data Privacy</h2>
        <p>The City Government of Santa Rosa is committed to protecting your personal data in strict compliance with <strong>Republic Act No. 10173 (Data Privacy Act of 2012)</strong>. The eRequest Mo Portal ensures your personal information and document requests are processed securely, lawfully, and transparently.</p>

        <hr>

        <h2>1. Information We Collect</h2>
        <p>To process your barangay inquiries, request certificates, and facilitate official city services, we collect:</p>
        <ul>
            <li><strong>Personal Identity Data:</strong> Full name, date of birth, gender, civil status, and residency details.</li>
            <li><strong>Contact Information:</strong> Active phone number, email address, and residential address.</li>
            <li><strong>Verification Documents:</strong> Uploaded government-issued valid IDs, photos, and prerequisite verification documents.</li>
            <li><strong>System & Logs:</strong> Session cookies, IP address, and security logs necessary to prevent fraud and maintain portal integrity.</li>
        </ul>

        <h2>2. Purpose & How We Use Your Data</h2>
        <p>Your personal information is processed exclusively for official municipal and barangay operations:</p>
        <ul>
            <li>Verifying your identity and residency within the City of Santa Rosa.</li>
            <li>Processing official barangay certificates, clearances, and document requests.</li>
            <li>Sending automated SMS or email updates regarding request statuses.</li>
            <li>Maintaining official system logs for administrative compliance and auditing.</li>
        </ul>

        <h2>3. Data Protection & Confidentiality</h2>
        <p>We implement strict technical, organizational, and physical security controls to guard your personal data against unauthorized access, loss, or alteration. We <strong>never sell, lease, or share</strong> your information with third-party commercial entities.</p>

        <h2>4. Your Data Subject Rights</h2>
        <p>Under the Data Privacy Act of 2012, you hold the following rights regarding your personal information:</p>
        <ul>
            <li><strong>Right to be Informed:</strong> Know how your data is collected and processed.</li>
            <li><strong>Right to Access & Rectification:</strong> Request access to your personal profile or correct inaccurate data.</li>
            <li><strong>Right to Object & Erasure:</strong> Object to processing or request account deletion subject to legal retention obligations.</li>
        </ul>

        <h2>5. Cookies and Browser Storage</h2>
        <p>The portal currently uses the following cookies. Essential session cookies support secure sign-in and portal functions. The notice preference cookie remembers whether you accepted or declined the notice; declining dismisses the notice but does not disable essential session or sign-in security cookies.</p>
        <ul>
            <li><strong>PHPSESSID:</strong> First-party session cookie used to associate your browser with a server-side session, including sign-in and security state. It is a session cookie and normally expires when you close your browser.</li>
            <li><strong>ei_cookie_consent:</strong> First-party cookie that records whether you accepted or declined the notice so it is not repeatedly shown. It expires after one year.</li>
            <li><strong>Google reCAPTCHA cookies:</strong> The sign-in and registration pages load Google reCAPTCHA to help protect against automated abuse. Google may set or read cookies when that third-party widget loads; Google controls their names and retention. See <a href="https://policies.google.com/privacy" target="_blank" rel="noopener noreferrer">Google Privacy Policy</a> and <a href="https://policies.google.com/terms" target="_blank" rel="noopener noreferrer">Google Terms</a>.</li>
        </ul>
        <p>The employee and administrator dashboards also use browser local storage to remember the selected dashboard panel. Local storage is separate from cookies and can be cleared through your browser settings.</p>

        <h2>6. Requests & Data Privacy Officer</h2>
        <p>If you have questions regarding your personal information or wish to exercise your data subject rights, please reach out to our team at the City Government Center, J.P. Rizal, City of Santa Rosa, Laguna.</p>



